/**
 * Bloom Capsule reward tables (GDD Section 8).
 *
 * Single-currency economy: Petal only. An earlier draft carried a second
 * "cosmeticShard" currency; it was removed so the Uncommon tier simply pays a
 * wider Petal range instead.
 *
 * The Petal AMOUNTS below are produced by tests/economy-calibration.js, which
 * tunes them until the one-time 2000-Petal 4th Card Slot lands ~15-20 runs
 * away. Do not hand-edit them — re-run the calibration script instead. The
 * TIER WEIGHTS are fixed design values from the GDD and are not calibrated.
 *
 * ANCHOR: a MID-SKILLED player averaging wave 8, not the reference bot. Skill
 * compounds here — deeper runs earn more small capsules and draw from a better
 * large-capsule band — so anchoring on the weak bot made the curve far too
 * generous for anyone competent (a strong player unlocked the slot in ~6 runs).
 * At this pool a mid player takes ~17 runs and the bot ~31.
 */

export const REWARD_TIERS = ['common', 'uncommon', 'rare', 'legendary'];

/** End-of-wave capsule: flat odds, no performance scaling, no pity. */
export const SMALL_CAPSULE_WEIGHTS = {
  common: 0.85,
  uncommon: 0.14,
  rare: 0.01,
  legendary: 0,
};

/**
 * End-of-run capsule: odds scale with how deep the run got (GDD Section 8).
 * Bands are inclusive on both ends.
 */
export const LARGE_CAPSULE_WEIGHTS_BY_PERFORMANCE = [
  { minWave: 1, maxWave: 4, weights: { common: 0.85, uncommon: 0.14, rare: 0.01, legendary: 0 } },
  { minWave: 5, maxWave: 9, weights: { common: 0.65, uncommon: 0.28, rare: 0.06, legendary: 0.01 } },
  { minWave: 10, maxWave: 999, weights: { common: 0.45, uncommon: 0.35, rare: 0.16, legendary: 0.04 } },
];

/**
 * What each tier actually pays out. Every entry in a tier's array is granted,
 * so Legendary hands over both the prestige skin and its Petal roll — that is
 * what makes the skin's drop rate equal to the Legendary tier rate (~1-4%)
 * rather than half of it.
 *
 * `amount: [min, max]` is an inclusive integer range.
 */
/* CALIBRATED_POOL_START — regenerated by tests/economy-calibration.js */
export const REWARD_POOL = {
  common: [{ type: 'petal', amount: [7, 14] }],
  uncommon: [{ type: 'petal', amount: [21, 35] }],
  rare: [{ type: 'petal', amount: [38, 59] }],
  legendary: [
    { type: 'cosmetic', id: 'prestij-skin' },
    { type: 'petal', amount: [105, 175] },
  ],
};
/* CALIBRATED_POOL_END */

/**
 * Weight row whose band contains `waveReached`.
 * @param {number} waveReached
 * @returns {{minWave: number, maxWave: number, weights: Object}}
 */
export function getLargeCapsuleBand(waveReached) {
  const wave = Math.max(1, Math.floor(waveReached) || 1);
  const band = LARGE_CAPSULE_WEIGHTS_BY_PERFORMANCE.find(
    (row) => wave >= row.minWave && wave <= row.maxWave
  );
  // Runs deeper than the last band's ceiling still get the top band.
  return band ?? LARGE_CAPSULE_WEIGHTS_BY_PERFORMANCE[LARGE_CAPSULE_WEIGHTS_BY_PERFORMANCE.length - 1];
}
